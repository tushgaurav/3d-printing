// Lucide has no hotend or heated bed, so these two are drawn here on Lucide's
// grid (24px, 2px round strokes) to sit alongside the others.
const CUSTOM = {
  nozzle: '<path d="M10 2v4"/><path d="M14 2v4"/><rect x="5" y="6" width="14" height="7" rx="2"/><path d="m9 13 2 5h2l2-5"/><path d="M12 21h.01"/>',
  bed: '<rect x="2" y="15" width="20" height="4" rx="1"/><path d="M7 12c2-3-2-3 0-6"/><path d="M12 12c2-3-2-3 0-6"/><path d="M17 12c2-3-2-3 0-6"/>',
};

async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

function inner(svg, name) {
  const m = svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/);
  if (!m) throw new Error(`${name}: not an SVG`);
  return m[1]
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s*\/>/g, '/>')
    .trim();
}

const entries = await Promise.all(Object.entries(ICONS).map(async ([ours, lucide]) => {
  const body = inner(await get(`${CDN}/icons/${lucide}.svg`), lucide);
  return [ours, body, lucide];
}));

const lines = [
  ...entries.map(([ours, body, lucide]) => `  ${JSON.stringify(ours)}: ${JSON.stringify(body)}, // ${lucide}`),
  ...Object.entries(CUSTOM).map(([ours, body]) => `  ${JSON.stringify(ours)}: ${JSON.stringify(body)}, // custom`),
];

const js = `// GENERATED by tools/build-icons.mjs - edit that script, not this file.
// Icons: Lucide v${VERSION} (ISC licence, see icons.LICENSE.txt), plus "nozzle" and
// "bed" drawn for this UI in Lucide's style. Usage: icon('home'), icon('play', 'cls')

const P = {
${lines.join('\n')}
};

export function icon(name, cls = '') {
  const body = P[name] || P.cube;
  return \`<svg class="i \${cls}" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
}
`;

await writeFile(OUT, js.replace(/\r\n/g, '\n'));
await writeFile(LICENSE_OUT, (await get(`${CDN}/LICENSE`)).replace(/\r\n/g, '\n'));
console.log(`Wrote ${entries.length + Object.keys(CUSTOM).length} icons to ${OUT}`);
